// Package eth defines interfaces for Ethereum blockchain operations.
package eth

import "context"

// =============================================================================
// MPC/TSS Port Interfaces (Pattern 4 — Threshold ECDSA)
//
// All types in this file use only Go primitives and context.Context.
// No TSS library types (tss-lib), gRPC types, or protobuf types appear here.
// The infrastructure layer implements these interfaces and is the sole location
// where TSS library imports are permitted.
// =============================================================================

// MPCSigningRequest carries the parameters for a single TSS signing session.
// All fields must be identical across all T participating nodes for a session to succeed.
type MPCSigningRequest struct {
	// SessionID is a UUIDv4 generated at session-initiation time.
	// Every TSS round message carries this ID to prevent cross-session routing.
	SessionID string

	// Hash is the 32-byte Keccak256 hash of the unsigned transaction (tx.Hash()).
	// TSS nodes sign this hash; the use case must pass exactly 32 bytes.
	Hash []byte

	// PartyIDs contains the sorted identifiers of all T participating nodes.
	// The order must be identical on all nodes for the GG18 protocol to succeed.
	PartyIDs []string

	// Threshold is T — the minimum number of signers required.
	Threshold int

	// PeerAddrs contains the gRPC listen addresses of all T nodes.
	// Index-matched with PartyIDs: PeerAddrs[i] is the address of PartyIDs[i].
	PeerAddrs []string
}

// MPCSigningResult carries the assembled ECDSA signature from a completed TSS session.
type MPCSigningResult struct {
	// SessionID echoes the input SessionID for correlation.
	SessionID string

	// Signature is the 65-byte Ethereum-compatible ECDSA signature: r[32] || s[32] || v[1].
	// The v byte is adjusted for EIP-155 (chain-ID-encoded) for Type-2 transactions,
	// or 27/28 for legacy transactions. types.Sender(signer, tx) must recover the correct address.
	Signature []byte
}

// MPCTransactionSigner is called by the Watch wallet to initiate a TSS signing session
// and collect the assembled 65-byte ECDSA signature.
//
// The implementation contacts all nodes listed in req.PeerAddrs, relays TSS protocol
// messages between them, and blocks until the session completes or ctx is cancelled.
// If fewer than req.Threshold nodes respond before ctx deadline, an error is returned
// and no partial signature is produced.
//
//nolint:iface // narrow interface intentionally paired with MPCCoordinatorDeps composed type
type MPCTransactionSigner interface {
	SignTransaction(ctx context.Context, req MPCSigningRequest) (*MPCSigningResult, error)
}

// DKGParams carries the configuration for a DKG ceremony on a single node.
type DKGParams struct {
	// PartyID is the identifier of this node within the session.
	PartyID string

	// AllPartyIDs contains the sorted identifiers of all N nodes (including this node).
	// Must be identical on every node in the ceremony.
	AllPartyIDs []string

	// Threshold is T — minimum signers needed for a future signing session.
	Threshold int

	// ListenAddr is the gRPC listen address for this node's P2P DKG server (e.g., "localhost:9001").
	// When non-empty, RunDKG starts a gRPC listener and connects to peers directly (P2P mode).
	// When empty, the coordinator relay model is used (backward-compatible).
	ListenAddr string

	// PeerAddrs contains the gRPC addresses of peer nodes (excluding self).
	// Index-matched with AllPartyIDs (self entry skipped): the i-th entry corresponds to
	// the i-th party in AllPartyIDs after removing PartyID.
	PeerAddrs []string

	// PreParamsPath is the filesystem path to the pre-computed Paillier pre-params file.
	// Generated by the standalone keygen pre-params command before DKG.
	PreParamsPath string

	// ShardOutputPath is the filesystem path where the encrypted shard will be written.
	ShardOutputPath string

	// Passphrase is used to derive the AES-256-GCM key for encrypting the shard file.
	Passphrase string
}

// DKGResult carries the output of a successfully completed DKG ceremony.
type DKGResult struct {
	// EthAddress is the EIP-55 checksummed joint Ethereum address derived from the joint public key.
	// All N nodes derive the same address independently; this is the distributed EOA address.
	EthAddress string

	// PublicKey is the 65-byte uncompressed secp256k1 joint public key.
	PublicKey []byte

	// ShardPath is the filesystem path where the encrypted shard was saved.
	ShardPath string
}

// MPCKeyGeneratorPort is called by the Keygen wallet CLI to run the DKG ceremony
// and to generate Paillier pre-computation parameters.
//
// Implementations wrap the tss-lib/v2 keygen package. Both methods are expected
// to be run by the node operator before any signing session.
//
//nolint:iface // narrow interface intentionally paired with MPCNodeDeps composed type
type MPCKeyGeneratorPort interface {
	// RunDKG runs the DKG ceremony for this node. Blocks until all N nodes complete
	// their respective rounds. Returns an error if any node aborts; no partial shard
	// is written on failure.
	RunDKG(ctx context.Context, params DKGParams) (*DKGResult, error)

	// GeneratePreParams generates the Paillier key pre-computation parameters and writes
	// them to outputPath as JSON. This is an expensive one-time operation per node.
	GeneratePreParams(ctx context.Context, outputPath string) error
}

// MPCKeyShardStorage abstracts encrypted shard file I/O for TSS key material.
//
// The shard file contains the node's LocalPartySaveData (from tss-lib/v2) and
// the associated pre-params, all encrypted as a single AES-256-GCM ciphertext.
// The passphrase is never stored; it is used at load time to derive the decryption key.
type MPCKeyShardStorage interface {
	// LoadShard decrypts and returns the opaque shard JSON bytes from shardPath.
	// The returned bytes are tss-lib/v2 LocalPartySaveData-compatible JSON.
	// Returns an error if the file is missing, corrupted, or the passphrase is wrong.
	LoadShard(ctx context.Context, shardPath string, passphrase string) ([]byte, error)

	// SaveShard encrypts data and writes the ciphertext to shardPath atomically.
	// data must be tss-lib/v2 LocalPartySaveData-compatible JSON.
	SaveShard(ctx context.Context, shardPath string, passphrase string, data []byte) error
}

// MPCOutboundTransport is used by the Watch wallet coordinator to send TSS round messages
// to individual MPC nodes and receive their responses.
//
// The coordinator opens connections to all T nodes, fans out the signing request,
// and acts as a message relay for all subsequent GG18 rounds.
type MPCOutboundTransport interface {
	// Send sends msg to the node at peerAddr. Used to relay TSS round messages.
	Send(ctx context.Context, peerAddr string, msg []byte) error

	// Receive returns a channel that delivers inbound messages from node responses.
	// The channel is closed when Close is called or ctx is cancelled.
	Receive(ctx context.Context) (<-chan []byte, error)

	// Close drains the receive channel and releases all gRPC connections.
	Close() error
}

// MPCInboundTransport is used by MPC node servers to accept incoming TSS round messages
// from the Watch wallet coordinator and to send TSS round messages back over the same
// bidirectional relay stream.
//
// Each MPC node starts this transport before awaiting signing sessions.
// The node reads from Receive() to drive the local tss-lib state machine and calls
// EnqueueOutbound to push outbound round messages back to the coordinator.
type MPCInboundTransport interface {
	// Listen starts the gRPC listener on listenAddr. Non-blocking after the port is bound.
	Listen(ctx context.Context, listenAddr string) error

	// Receive returns a channel that delivers inbound TSS round messages from the coordinator.
	// The channel is closed when Close is called or ctx is cancelled.
	Receive(ctx context.Context) (<-chan []byte, error)

	// EnqueueOutbound queues msg to be sent to the coordinator over the active RelaySession
	// stream. Returns an error if the outbound send buffer is full.
	EnqueueOutbound(msg []byte) error

	// Close gracefully stops the gRPC listener and closes the receive channel.
	Close() error
}

// MPCSessionRequest is the first message sent by the Watch wallet coordinator to a signing node
// to initiate a new signing session. It carries the transaction data so that the node can verify
// the hash before participating in the TSS protocol.
//
// The node unmarshals the first message from MPCInboundTransport.Receive() as MPCSessionRequest
// and computes hash(RawTxHex) to validate it matches TxHash. If they do not match, the node
// aborts and returns ErrTxHashMismatch.
type MPCSessionRequest struct {
	// SessionID is a UUIDv4 that uniquely identifies this signing session.
	SessionID string `json:"session_id"`

	// TxHash is the 0x-prefixed hex hash of the unsigned transaction (RawTxHex decoded → tx.Hash()).
	TxHash string `json:"tx_hash"`

	// RawTxHex is the 0x-prefixed hex-encoded RLP of the unsigned transaction.
	// The node verifies hash(RawTxHex) == TxHash before participating.
	RawTxHex string `json:"raw_tx_hex"`

	// PartyIDs contains the sorted identifiers of all T participating nodes.
	PartyIDs []string `json:"party_ids"`

	// Threshold is T — minimum signers required.
	Threshold int `json:"threshold"`
}

