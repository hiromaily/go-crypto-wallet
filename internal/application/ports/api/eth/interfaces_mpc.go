// MPCCoordinatorDeps is the composed interface injected into the Watch wallet DI binding.
// It embeds MPCTransactionSigner, which is the only MPC capability the Watch wallet needs.
// Additional interfaces may be embedded here in the future without changing use cases.
//
//nolint:iface // intentional single-embed composition for DI and compile-time checks
type MPCCoordinatorDeps interface {
	MPCTransactionSigner
}

// MPCNodeDeps is the composed interface injected into the Keygen/Sign node DI binding.
// It embeds MPCKeyGeneratorPort, which covers both DKG and pre-param generation.
//
//nolint:iface // intentional single-embed composition for DI and compile-time checks
type MPCNodeDeps interface {
	MPCKeyGeneratorPort
}
