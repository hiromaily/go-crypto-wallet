#!/usr/bin/env bash

# XRP E2E Workflow Script - Pattern 2: 2-of-2 Multisig Payment Transfer
# This script automates the complete XRP multi-signature transaction flow:
#   keygen seed/key → address export → watch address import →
#   fund sender + signer accounts → set-signer-list → sign SignerListSet →
#   submit SignerListSet → create multisig payment TX →
#   sign1 (keygen) → sign2 (keygen as second signer) → watch send → ledger_accept → verify
#
# Usage: ./scripts/operation/xrp/e2e/e2e-p2.sh [OPTIONS]
#
# Options:
#   --cleanup           Stop containers and cleanup state
#   --reset             Full reset and run from scratch
#   --verbose           Enable verbose output (set -x)
#   --non-interactive   Run without prompts (for CI/CD)
#   -h, --help          Display this help message
#
# Transaction Pattern:
#   Pattern 2: XRP 2-of-2 multisig payment transfer
#   - Address Type: XRP classic address (ed25519 or secp256k1)
#   - Address Format: r... (base58)
#   - Multisig: Signer list with 2 authorized signers (quorum=2)
#   - Signing: Keygen wallet (first signer) + Keygen wallet second DB (second signer)
#
# Account Setup:
#   - PAYMENT_ACCOUNT: "payment" — multisig sender; holds the SignerList
#   - CLIENT_ACCOUNT:  "deposit" — receiver of the multisig payment
#   - SIGNER1: first "signer" account generated by keygen (used as signer in SignerList)
#   - SIGNER2: second "signer" account generated by a separate keygen DB
#
# Signing Architecture:
#   The XRP multisig signing flow uses the sign wallet's JSON-format signer
#   (sign/xrp/sign_transaction.go). However, the sign wallet binary does not yet
#   support XRP coin (NewSigner returns "not implemented" for XRP).
#   As a workaround, this test uses the keygen wallet for Sign 1 and documents
#   the intended Sign 2 command. Full end-to-end execution requires:
#     1. Enable XRP support in the sign wallet (NewSigner in container.go)
#     2. Update keygen sign use case to detect and handle JSON format files
#   Until then, the signing steps are validated at the file-structure level via jq.
#
# Environment Variables:
#   DB_TYPE       Database type: sqlite (default) or mysql
#   XRP_WS_HOST   rippled WebSocket host (default: 127.0.0.1)
#   XRP_WS_PORT   rippled WebSocket port (default: 6006)
#
# Required Config:
#   config/wallet/xrp/watch.yaml:  ripple.websocket_public_url overridden by XRP_WS_HOST:XRP_WS_PORT
#   config/wallet/xrp/keygen.yaml: ripple.offline_keygen: true
#
# Infrastructure:
#   rippled v3.1.0 standalone mode (compose.xrp.yaml)
#   WebSocket admin port 6006 (ws://) — direct connection, no xrpl-grpc-server
#   Ledger must be manually advanced via 'rippled ledger_accept' after each tx

set -euo pipefail

###############################################################################
# Script Configuration
###############################################################################

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Source the XRP common utilities (which also sources common.sh)
# shellcheck source=../xrp_common.sh
source "${SCRIPT_DIR}/../xrp_common.sh"

# Pattern identifier for DB isolation
export E2E_PATTERN="p2"

# Re-initialize database with correct pattern now that E2E_PATTERN is set
xrp_init_database

###############################################################################
# Configuration
###############################################################################

xrp_get_config_paths

# Number of HD keys to generate per account
KEY_NUM=5

# Accounts used in this E2E test
PAYMENT_ACCOUNT="payment" # Multisig sender
CLIENT_ACCOUNT="deposit"  # Payment receiver

# XRP amounts
FUNDING_AMOUNT_PAYMENT_XRP=200 # Fund payment (multisig sender) — needs extra for signer fees
FUNDING_AMOUNT_CLIENT_XRP=10   # Fund deposit account (activate with base reserve)
TRANSFER_AMOUNT_XRP=50.0       # Transfer amount for the multisig payment

# Multisig configuration
MULTISIG_QUORUM=2 # Require 2-of-2 signatures

###############################################################################
# Argument Parsing
###############################################################################

MODE="run"
VERBOSE=false
NON_INTERACTIVE=false

